// Generates src/lib/icons.ts from Phosphor (MIT): path data only, so icons
// render as plain <path> elements without injecting HTML.
//   npm run icons
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../node_modules/@phosphor-icons/core/assets/', import.meta.url);

// UI icons (regular weight)
const ui = [
  'check', 'x', 'trash', 'shield-check', 'shield-warning', 'sign-out', 'sign-in', 'info', 'bell', 'bell-slash', 'warning',
  'warning-circle', 'check-circle', 'question', 'star', 'gear-six', 'arrows-clockwise', 'pencil-simple', 'globe-simple',
  'pulse', 'wifi-slash', 'wifi-high', 'user-plus', 'shuffle', 'paper-plane-tilt', 'magnifying-glass', 'power', 'plus',
  'git-merge', 'lock-simple', 'squares-four', 'key', 'dots-three', 'download-simple', 'copy', 'caret-right',
  'caret-down', 'caret-left', 'arrow-left', 'devices', 'clock-counter-clockwise', 'list-bullets', 'moon', 'sun',
  'broadcast', 'heartbeat', 'arrow-square-out', 'eye', 'eye-slash', 'funnel', 'circle-half',
];
// Device glyphs (duotone)
const devices = [
  'wifi-high', 'network', 'hard-drives', 'database', 'desktop-tower', 'laptop', 'device-mobile', 'device-tablet',
  'watch', 'television-simple', 'screencast', 'speaker-hifi', 'game-controller', 'printer', 'security-camera',
  'house-line', 'lightbulb', 'plug', 'cpu', 'cube', 'question',
];

function paths(file) {
  const svg = readFileSync(new URL(file, dir), 'utf8');
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const out = [];
  for (const m of body.matchAll(/<(\w+)([^>]*)\/>/g)) {
    if (m[1] !== 'path') throw new Error(`${file}: unsupported element <${m[1]}>`);
    const d = /\sd="([^"]+)"/.exec(m[2])?.[1];
    const op = /\sopacity="([^"]+)"/.exec(m[2])?.[1];
    out.push(op ? [d, Number(op)] : [d]);
  }
  if (!out.length || body.replace(/<path[^>]*\/>/g, '').trim()) throw new Error(`${file}: unexpected content`);
  return out;
}

let ts = '// Generated by scripts/gen-icons.mjs from Phosphor Icons (MIT, phosphoricons.com). Do not edit.\n\n';
ts += '// [path, opacity (duotone fill), stroked]: stroked paths use the Phosphor 16-unit line.\n';
ts += 'export type IconPath = [d: string, opacity?: number, stroke?: boolean];\n\n';
ts += 'export const icons: Record<string, IconPath[]> = {\n';
for (const n of ui) ts += `  '${n}': ${JSON.stringify(paths(`regular/${n}.svg`))},\n`;
ts += `  'fill:star': ${JSON.stringify(paths('fill/star-fill.svg'))},\n`;
for (const n of devices) ts += `  'duo:${n}': ${JSON.stringify(paths(`duotone/${n}-duotone.svg`))},\n`;
// Phosphor has no router glyph; drawn in its duotone style (256 grid, 16-unit stroke).
const routerBody = 'M40,136H216a16,16,0,0,1,16,16v40a16,16,0,0,1-16,16H40a16,16,0,0,1-16-16V152A16,16,0,0,1,40,136Z';
ts += `  'duo:router': ${JSON.stringify([
  [routerBody, 0.2],
  [routerBody, 1, true],
  ['M72,136,56,56', 1, true],
  ['M184,136l16-80', 1, true],
  ['M116,172h0', 1, true],
  ['M76,172h0', 1, true],
  ['M160,172h32', 1, true],
])},\n`;
ts += '};\n';
writeFileSync(new URL('../src/lib/icons.ts', import.meta.url), ts);
console.log(`wrote ${ui.length + devices.length} icons`);
