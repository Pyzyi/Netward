const dicts = { de, en } as const;
export type Lang = keyof typeof dicts;

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('netzwart.lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export const i18n = $state<{ lang: Lang }>({ lang: initialLang() });

export function setLang(l: Lang) {
  i18n.lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem('netzwart.lang', l);
  } catch {
    /* ignore */
  }
}

/** Translate key, replacing {placeholders}. */
export function t(key: Key | string, vars?: Record<string, string | number>): string {
  const d = dicts[i18n.lang] as Record<string, string>;
  let s = d[key] ?? (de as Record<string, string>)[key] ?? key;
  if (vars) {
    // "{n|Gerät|Geräte}" picks the singular when n is 1.
    s = s.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k: string, one: string, many: string) => (Number(vars[k]) === 1 ? one : many));
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function has(key: string): boolean {
  return key in dicts[i18n.lang];
}

const locale = () => (i18n.lang === 'de' ? 'de-DE' : 'en-GB');

/** "vor 3 Minuten" / "3 minutes ago". */
export function relTime(ms: number, now: number): string {
  if (!ms) return t('common.never');
  const diff = Math.round((ms - now) / 1000);
  const abs = Math.abs(diff);
  if (abs < 45) return t('common.now');
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: 'auto' });
  if (abs < 3600) return rtf.format(Math.round(diff / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), 'hour');
  if (abs < 86400 * 30) return rtf.format(Math.round(diff / 86400), 'day');
  return dateTime(ms);
}

/** Compact duration: "3 h 20 min", "5 Tage". */
export function duration(ms: number): string {
  const min = Math.max(0, Math.round(ms / 60000));
  if (min < 1) return t('common.seconds', { n: Math.max(1, Math.round(ms / 1000)) });
  if (min < 60) return t('common.minutes', { n: min });
  const h = Math.floor(min / 60);
  if (h < 48) {
    const m = min % 60;
    return m ? `${t('common.hours', { n: h })} ${t('common.minutes', { n: m })}` : t('common.hours', { n: h });
  }
  return t('common.days', { n: Math.floor(h / 24) });
}

/** Duration after "seit"/"for": German needs the dative ("seit 3 Tagen"). */
export function durationSince(ms: number): string {
  const days = Math.floor(ms / 86400000);
  if (days >= 2) return t('common.sinceDays', { n: days });
  if (days === 1 && ms >= 36 * 3600000) return t('common.sinceDay');
  return duration(ms);
}

/** A time ahead as words: "in 3 Monaten", "in 2 years". */
export function inFuture(ms: number): string {
  const days = Math.round(ms / 86400000);
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: 'auto' });
  if (days < 60) return rtf.format(days, 'day');
  if (days < 730) return rtf.format(Math.round(days / 30.44), 'month');
  return rtf.format(Math.round(days / 365.25), 'year');
}

/** "2026-10-13" as a long local date ("13. Oktober 2026"). */
export function dateLong(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  if (!y || !m || !d) return iso;
  return new Intl.DateTimeFormat(locale(), { dateStyle: 'long' }).format(new Date(y, m - 1, d));
}

export function dateTime(ms: number): string {
  return new Intl.DateTimeFormat(locale(), { dateStyle: 'medium', timeStyle: 'short' }).format(ms);
}

export function time(ms: number): string {
  return new Intl.DateTimeFormat(locale(), { timeStyle: 'short' }).format(ms);
}

export function dayLabel(ms: number, now: number): string {
  const d = new Date(ms);
  const today = new Date(now);
  const startOf = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const days = Math.round((startOf(today) - startOf(d)) / 86400000);
  if (days === 0) return t('activity.today');
  if (days === 1) return t('activity.yesterday');
  return new Intl.DateTimeFormat(locale(), { weekday: 'long', day: 'numeric', month: 'long' }).format(ms);
}

/** Day of `ms` as a short tag for tight columns: '' today, "Gestern", else "Sa., 24.". */
export function shortDay(ms: number, now: number): string {
  const startOf = (x: number) => {
    const d = new Date(x);
    return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
  };
  const days = Math.round((startOf(now) - startOf(ms)) / 86400000);
  if (days === 0) return '';
  if (days === 1) return t('activity.yesterday');
  return new Intl.DateTimeFormat(locale(), { weekday: 'short', day: 'numeric' }).format(ms);
}

export function number(n: number): string {
  return new Intl.NumberFormat(locale()).format(n);
}

export function bytes(n: number): string {
  const units = ['B', 'KB', 'MB', 'GB'];
  let i = 0;
  while (n >= 1024 && i < units.length - 1) {
    n /= 1024;
    i++;
  }
  return `${new Intl.NumberFormat(locale(), { maximumFractionDigits: 1 }).format(n)} ${units[i]}`;
}
